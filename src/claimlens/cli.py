def cmd_record_read2(args: argparse.Namespace) -> int:
    from pathlib import Path

    from claimlens import hard_eval

    samples_dir = Path("samples")
    wanted = tuple(s.strip() for s in args.samples.split(",")) if args.samples else None
    samples = wanted or hard_eval.NORMAL_SAMPLES
    plan = hard_eval.plan_read2(samples_dir, samples)
    missing = plan["missing"]
    lines = ["Second-read recordings for the double-read gate (new .read2 keys only):",
             (f"{missing} of {len(plan['pairs'])} pairs missing; "
              "cached pairs are skipped, existing files never overwritten."),
             f"git status cache/: {hard_eval.git_cache_status()}",
             f"estimate: {missing} x ${hard_eval.BASE_EST:.4f} = ${missing * hard_eval.BASE_EST:.2f}."]
    if not args.execute:
        lines.append("Stopped before any API call. Re-run with --execute to record.")
        _emit("\n".join(lines))
        return 0
    from dotenv import load_dotenv

    load_dotenv()
    before = hard_eval.git_cache_status()
    done = hard_eval.record_read2(plan["pairs"], samples_dir,
                                  hard_eval.default_provider_factory())
    lines.append(f"recorded {len(done['stored'])}: {', '.join(done['stored'])}; "
                 f"spent ${done['spent']:.4f}.")
    lines.append(f"cache/ before: {before}")
    lines.append(f"cache/ after: {hard_eval.git_cache_status()}")
    _emit("\n".join(lines))
    return 0


