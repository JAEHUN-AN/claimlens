def _emit(text: str, end: str = "\n") -> None:
    """Print, surviving consoles that cannot encode the text (e.g. cp949)."""
    try:
        print(text, end=end)
    except UnicodeEncodeError:
        print("claimlens: this console cannot show the output text.", file=sys.stderr)


def receipt_checks(envelope: dict[str, Any]) -> list[dict[str, Any]] | None:
    docs = envelope["result"].get("documents", [])
    bills = [(i, d["kr_bill"]) for i, d in enumerate(docs) if d.get("kr_bill")]
    if not bills:
        return None
    out = []
    for i, bill in bills:
        checks = check_kr_bill(bill)
        out.append(
            {
                "document": i,
                "all_passed": all_passed(checks),
                "checks": [asdict(c) for c in checks],
            }
        )
    return out


def verify_envelope(
    sample: str, variant: str, envelope: dict[str, Any]
) -> list[dict[str, Any]] | None:
    from pathlib import Path

    from claimlens.reader import get_provider, resolve_sample_images
    from claimlens.verify import verify_receipt

    docs = envelope["result"].get("documents", [])
    bills = [(i, d) for i, d in enumerate(docs) if d.get("kr_bill")]
    if not bills:
        return None
    images = resolve_sample_images(Path(sample), variant)
    provider = get_provider()
    out = []
    for i, doc in bills:
        result = verify_receipt(doc, images[i], provider)
        entry: dict[str, Any] = {
            "document": i,
            "status": result["status"],
            "corrected": result["corrected"],
            "checks": [asdict(c) for c in result["checks"]],
        }
        if "failed_before" in result:
            entry["failed_before"] = result["failed_before"]
            entry["receipt"] = result["receipt"]
        if "failing" in result:
            entry["failing"] = result["failing"]
        out.append(entry)
    for entry in out:
        entry["calls"] = [vars(c) for c in provider.calls]
    return out


def cmd_read(args: argparse.Namespace) -> int:
    try:
        envelope = read_sample(args.sample, args.variant)
        envelope["receipt_checks"] = receipt_checks(envelope)
        envelope["verification"] = verify_envelope(args.sample, args.variant, envelope)
    except (FileNotFoundError, RuntimeError, LookupError, ValidationError) as exc:
        print(f"claimlens: {exc}", file=sys.stderr)
        return 1
    _emit(json.dumps(envelope, ensure_ascii=False, indent=2))
    return 0


def cmd_eval(args: argparse.Namespace) -> int:
    from claimlens.eval import eval_all, format_markdown, format_open_section, open_translation_row

    if args.set is None and args.repeat == 1:
        rows = eval_all()
        text = format_markdown(rows) + "\n" + format_open_section(open_translation_row())
        if args.output:
            with open(args.output, "w", encoding="utf-8") as handle:
                handle.write("# ClaimLens reading accuracy\n\n")
                handle.write("All documents are synthetic. Generated by `claimlens eval`.\n\n")
                handle.write(text)
        _emit(text, end="")
        return 0
    return cmd_repeat_eval(args)


def cmd_repeat_eval(args: argparse.Namespace) -> int:
    from pathlib import Path

    from claimlens import hard_eval
    from claimlens.eval import ground_truth, load_scenarios
    from claimlens.hard_images import HARD_SAMPLES, TRANSFORMS
    from claimlens.reader import resolve_sample_images

    samples_dir = Path("samples")
    out_dir = Path("out") / "hard"
    scenarios = load_scenarios()
    picked_samples = tuple(s.strip() for s in args.samples.split(",")) if args.samples else None
    picked_transforms = (
        tuple(s.strip() for s in args.transforms.split(",")) if args.transforms else TRANSFORMS
    )
    for name in picked_transforms:
        if name not in TRANSFORMS:
            print(f"claimlens: unknown transform {name!r}.", file=sys.stderr)
            return 2
    plans = {}
    if args.set in (None, "normal"):
        wanted = picked_samples or hard_eval.NORMAL_SAMPLES
        plans["normal"] = hard_eval.plan_normal(samples_dir, args.repeat, wanted)
    if args.set in (None, "hard"):
        wanted = picked_samples or HARD_SAMPLES
        unknown = [s for s in wanted if s not in HARD_SAMPLES]
        if unknown:
            print(f"claimlens: hard set starts with {', '.join(HARD_SAMPLES)}; "
                  f"unknown: {', '.join(unknown)}.", file=sys.stderr)
            return 2
        plans["hard"] = hard_eval.plan_hard(args.seed, out_dir, samples_dir, args.repeat,
                                             wanted, picked_transforms)
    lines = ["Hard/normal repeat eval plan (no network calls made):",
             "cache/hard recordings: new files only; committed cache/ stays untouched.",
             f"git status cache/: {hard_eval.git_cache_status()}"]
    for name, plan in plans.items():
        lines.append(hard_eval.estimate_text(plan, f"{name} set x{args.repeat}"))
    base = sum(p["base_live"] for p in plans.values())
    re_max = sum(p["reread_max"] for p in plans.values())
    lines.append(f"TOTAL live calls: {base} base + up to {re_max} re-reads; "
                 f"estimate ${base * hard_eval.BASE_EST:.2f}"
                 f"-${base * hard_eval.BASE_EST + re_max * hard_eval.REREAD_EST:.2f} "
                 f"(base reads at the ${hard_eval.BASE_EST:.4f} median of docs/eval.md).")
    if not args.execute:
        lines.append("Stopped before any API call. Re-run with --execute to run it.")
        _emit("\n".join(lines))
        return 0
    from dotenv import load_dotenv

    load_dotenv()
    for name, plan in plans.items():
        for case in plan["cases"]:
            truth = ground_truth(scenarios[case["sample"]])
            if name == "hard":
                images = [out_dir / case["receipt"], out_dir / case["cert"]]
                unreadable = case["unreadable"]
            else:
                images = resolve_sample_images(samples_dir / case["sample"], case["variant"])
                unreadable = {"total": False, "line_amounts": False, "kr_cells": []}
            case["images"] = images
            case["truth"] = truth
            case["unreadable"] = unreadable
    results = hard_eval.execute(plans, args.repeat, args.max_cost,
                                hard_eval.default_provider_factory(),
                                hard_eval.run_log_path())
    text = "\n".join(lines) + "\n\n" + hard_eval.format_tables(results, args.repeat)
    text += f"\ncache/ before: {results['cache_before']}\ncache/ after: {results['cache_after']}\n"
    if args.output:
        with open(args.output, "w", encoding="utf-8") as handle:
            handle.write(text)
    _emit(text, end="")
    return 0


