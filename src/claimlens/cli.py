def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="claimlens")
    sub = parser.add_subparsers(dest="command", required=True)
    read = sub.add_parser("read", help="Read the receipt and certificate of a sample folder.")
    read.add_argument("sample", help="Sample folder, e.g. samples/A_niseko_wrist.")
    read.add_argument("--variant", choices=["photo", "clean"], default="photo")
    read.set_defaults(func=cmd_read)
    evaluation = sub.add_parser("eval", help="Accuracy table over all samples and variants.")
    evaluation.add_argument("--output", default=None, help="Write the table to a Markdown file.")
    evaluation.add_argument("--set", choices=["normal", "hard"], default=None,
                            help="Repeat-eval set (default runs the legacy table).")
    evaluation.add_argument("--repeat", type=int, default=1,
                            help="Runs per image for run-to-run agreement.")
    evaluation.add_argument("--execute", action="store_true",
                            help="Actually run; without it only the plan prints.")
    evaluation.add_argument("--samples", default=None,
                            help="Comma-separated sample ids (default: the whole set).")
    evaluation.add_argument("--transforms", default=None,
                            help="Comma-separated hard transforms (default: all eight).")
    evaluation.add_argument("--seed", type=int, default=41)
    evaluation.add_argument("--max-cost", type=float, default=1.00,
                            help="Abort the run past this spend in USD.")
    evaluation.set_defaults(func=cmd_eval)
    report = sub.add_parser("eval-report", help="Recompute eval tables from a run log.")
    report.add_argument("log", help="Run log JSON, e.g. out/hard_eval_....json.")
    report.add_argument("--repeat", type=int, default=3)
    report.add_argument("--output", default=None, help="Write the tables to a Markdown file.")
    report.set_defaults(func=cmd_eval_report)
    read2 = sub.add_parser("record-read2", help="Record second reads under .read2 keys.")
    read2.add_argument("--samples", default=None, help="Comma-separated sample ids.")
