"""CLI: uv run claimlens read|eval ... ."""

import argparse
import json
import sys
from dataclasses import asdict
from typing import Any

from pydantic import ValidationError

from claimlens.checks import all_passed, check_kr_bill
from claimlens.reader import read_sample


def _emit(text: str, end: str = "\n") -> None:
    """Print, surviving consoles that cannot encode the text (e.g. cp949)."""
    try:
        print(text, end=end)
    except UnicodeEncodeError:
        print("claimlens: this console cannot show the output text.", file=sys.stderr)


def receipt_checks(envelope: dict[str, Any]) -> list[dict[str, Any]] | None:
    docs = envelope["result"].get("documents", [])
    bills = [(i, d["kr_bill"]) for i, d in enumerate(docs) if d.get("kr_bill")]
    if not bills:
        return None
    out = []
    for i, bill in bills:
        checks = check_kr_bill(bill)
        out.append(
            {
                "document": i,
                "all_passed": all_passed(checks),
                "checks": [asdict(c) for c in checks],
            }
        )
    return out


def verify_envelope(
    sample: str, variant: str, envelope: dict[str, Any]
) -> list[dict[str, Any]] | None:
    from pathlib import Path

    from claimlens.reader import get_provider, resolve_sample_images
    from claimlens.verify import verify_receipt

    docs = envelope["result"].get("documents", [])
    bills = [(i, d) for i, d in enumerate(docs) if d.get("kr_bill")]
    if not bills:
        return None
    images = resolve_sample_images(Path(sample), variant)
    provider = get_provider()
    out = []
    for i, doc in bills:
        result = verify_receipt(doc, images[i], provider)
        entry: dict[str, Any] = {
            "document": i,
            "status": result["status"],
            "corrected": result["corrected"],
            "checks": [asdict(c) for c in result["checks"]],
        }
        if "failed_before" in result:
            entry["failed_before"] = result["failed_before"]
            entry["receipt"] = result["receipt"]
        if "failing" in result:
            entry["failing"] = result["failing"]
        out.append(entry)
    for entry in out:
        entry["calls"] = [vars(c) for c in provider.calls]
    return out


def cmd_read(args: argparse.Namespace) -> int:
    try:
        envelope = read_sample(args.sample, args.variant)
        envelope["receipt_checks"] = receipt_checks(envelope)
        envelope["verification"] = verify_envelope(args.sample, args.variant, envelope)
    except (FileNotFoundError, RuntimeError, LookupError, ValidationError) as exc:
        print(f"claimlens: {exc}", file=sys.stderr)
        return 1
    _emit(json.dumps(envelope, ensure_ascii=False, indent=2))
    return 0


def cmd_eval(args: argparse.Namespace) -> int:
    from claimlens.eval import eval_all, format_markdown, format_open_section, open_translation_row

    rows = eval_all()
    text = format_markdown(rows) + "\n" + format_open_section(open_translation_row())
    if args.output:
        with open(args.output, "w", encoding="utf-8") as handle:
            handle.write("# ClaimLens reading accuracy\n\n")
            handle.write("All documents are synthetic. Generated by `claimlens eval`.\n\n")
            handle.write(text)
    _emit(text, end="")
    return 0


def cmd_agent_eval(args: argparse.Namespace) -> int:
    from claimlens.agent_eval import eval_all, format_markdown

    rows = eval_all(live=args.live)
    text = format_markdown(rows)
    if args.output:
        with open(args.output, "w", encoding="utf-8") as handle:
            handle.write("# ClaimLens agent scorecard\n\n")
            handle.write("All cases replay recorded dialogues. Generated by ")
            handle.write("`claimlens agent-eval`.\n\n")
            handle.write(text)
            handle.write("\nNotes:\n\n")
            handle.write("- Each case is one recorded dialogue replayed, not repeated runs.\n")
            handle.write(
                "- confirm-voice-date is the voice-intake rule asking for "
                "confirmation, not the agent loop (0 steps).\n"
            )
    _emit(text, end="")
    return 0


def cmd_adjudicate(args: argparse.Namespace) -> int:
    from claimlens.engine import adjudicate_sample

    try:
        envelope = adjudicate_sample(args.sample_id, args.variant)
    except (FileNotFoundError, RuntimeError, LookupError, ValueError) as exc:
        print(f"claimlens: {exc}", file=sys.stderr)
        return 1
    _emit(json.dumps(envelope, ensure_ascii=False, indent=2))
    return 0


def cmd_rationale(args: argparse.Namespace) -> int:
    from claimlens.rationale import build_rationale, format_card, rationale_provider_default

    try:
        card = build_rationale(args.sample_id, args.variant, rationale_provider_default())
    except (FileNotFoundError, RuntimeError, LookupError, ValueError) as exc:
        print(f"claimlens: {exc}", file=sys.stderr)
        return 1
    text = format_card(card)
    if args.output:
        with open(args.output, "w", encoding="utf-8") as handle:
            handle.write(text)
    _emit(text, end="")
    return 0


def cmd_claimpack(args: argparse.Namespace) -> int:
    from claimlens.claimpack import build_pack, format_html, format_markdown
    from claimlens.rationale import rationale_provider_default

    try:
        pack = build_pack(
            args.sample_id, args.variant, rationale_provider_default(), lang=args.lang
        )
    except (FileNotFoundError, RuntimeError, LookupError, ValueError) as exc:
        print(f"claimlens: {exc}", file=sys.stderr)
        return 1
    text = format_html(pack) if args.format == "html" else format_markdown(pack)
    if args.output:
        with open(args.output, "w", encoding="utf-8") as handle:
            handle.write(text)
    _emit(text, end="")
    return 0


def cmd_mask(args: argparse.Namespace) -> int:
    from pathlib import Path

    from claimlens.masking import mask_sample_image

    try:
        result = mask_sample_image(
            args.sample_id, args.variant, args.doc, args.phrase, Path(args.output)
        )
    except (FileNotFoundError, RuntimeError, LookupError) as exc:
        print(f"claimlens: {exc}", file=sys.stderr)
        return 1
    _emit(json.dumps(result, ensure_ascii=False, indent=2))
    return 0


def cmd_demo(args: argparse.Namespace) -> int:
    from pathlib import Path

    from claimlens.demo import export_demo

    try:
        path = export_demo(Path(args.output))
    except (FileNotFoundError, RuntimeError, LookupError, ValueError) as exc:
        print(f"claimlens: {exc}", file=sys.stderr)
        return 1
    print(str(path))
    return 0


def cmd_mcp(args: argparse.Namespace) -> int:
    from claimlens.mcp import main as serve_mcp

    serve_mcp()
    return 0


def cmd_serve(args: argparse.Namespace) -> int:
    from claimlens.serve import serve_forever

    serve_forever(args.port)
    return 0


def cmd_probe_files(args: argparse.Namespace) -> int:
    from claimlens.probe import probe_files
    from claimlens.providers.meta import MetaProvider

    try:
        summary = probe_files(args.image, args.out, MetaProvider)
    except (FileNotFoundError, RuntimeError, ValueError) as exc:
        print(f"claimlens: {exc}", file=sys.stderr)
        return 1
    _emit(f"files_api: {summary['files_api']}")
    _emit(f"input: {summary['input']}")
    tokens = summary["tokens"]
    _emit(
        f"tokens: {tokens.get('total_tokens', 0)} "
        f"(in {tokens.get('input_tokens', 0)} / out {tokens.get('output_tokens', 0)})"
    )
    _emit(f"documents: {summary['documents']}")
    _emit(f"wrote: {summary['wrote']}")
    return 0


